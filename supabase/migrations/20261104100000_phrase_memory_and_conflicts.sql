-- ═══════════════════════════════════════════════════════════════
-- 1) Phrase Memory  — พจนานุกรมวลีที่เรียนรู้จากผล AI (พร้อม grounding ซ้ำ)
-- 2) Conflict Queue — คิวให้คนตรวจเมื่อ AI ขัดกับหลักฐาน
-- ═══════════════════════════════════════════════════════════════
-- หลักการ:
--  - ไม่เก็บซ้ำข้อมูลสินค้า: ทั้งสองตารางเก็บเฉพาะ "ความรู้ที่ใช้ซ้ำได้"
--  - phrase เก็บแบบ normalized (ตัวพิมพ์เล็ก, ช่องว่างเดียว) — การจับคู่จริง
--    ต้องสแกนหาวลีในข้อความสินค้าใหม่ทุกครั้ง (grounding) ไม่ใช่เชื่อ cache ตรง ๆ
--  - conflict เก็บแบบ idempotent ด้วย UNIQUE(ext, attribute, value_id)
--    → รัน pipeline ซ้ำไม่สร้างแถวซ้ำ และไม่เปิดของที่คนปิดไปแล้ว
--  - ค่าทั้งหมดอ้าง vocabulary กลาง (enum-only) — ไม่มีตัวเลข/การวัดในตารางนี้
-- ปลอดภัย: CREATE TABLE IF NOT EXISTS เท่านั้น ไม่แตะตารางเดิม
-- ย้อนกลับ: DROP TABLE public.enrichment_conflicts, public.enrichment_phrases;
-- ═══════════════════════════════════════════════════════════════

-- ── 1) Phrase Memory ───────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.enrichment_phrases (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- attribute|value_id|category|phrase  (คำนวณฝั่งแอป เพื่อ upsert ได้ตรง)
  phrase_key   TEXT NOT NULL UNIQUE,
  phrase       TEXT NOT NULL,
  attribute    TEXT NOT NULL,
  value_id     TEXT NOT NULL,
  value_label  TEXT NOT NULL DEFAULT '',
  category     TEXT,
  product_type TEXT,
  observations INT NOT NULL DEFAULT 0,
  accept       INT NOT NULL DEFAULT 0,
  reject       INT NOT NULL DEFAULT 0,
  confidence   NUMERIC(3,2) NOT NULL DEFAULT 0.60,
  status       TEXT NOT NULL DEFAULT 'candidate'
               CHECK (status IN ('candidate', 'active', 'blocked')),
  origin       TEXT NOT NULL DEFAULT 'ai'
               CHECK (origin IN ('ai', 'vision', 'phrase', 'manual')),
  first_seen   TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_seen    TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.enrichment_phrases IS
  'พจนานุกรมวลีที่เรียนรู้จาก quote ของ AI — ต้องสแกนยืนยันในข้อความจริงทุกครั้งก่อนใช้ (grounding)';
COMMENT ON COLUMN public.enrichment_phrases.status IS
  'candidate = ยังไม่พอหลักฐาน · active = ใช้ได้ · blocked = ถูกปฏิเสธบ่อย (ห้ามใช้)';

CREATE INDEX IF NOT EXISTS idx_phrases_status ON public.enrichment_phrases(status, attribute);
CREATE INDEX IF NOT EXISTS idx_phrases_category ON public.enrichment_phrases(category) WHERE status = 'active';
CREATE INDEX IF NOT EXISTS idx_phrases_last_seen ON public.enrichment_phrases(last_seen DESC);

ALTER TABLE public.enrichment_phrases DISABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.enrichment_phrases TO anon, authenticated;

-- ── 2) Conflict Queue (Human Review) ───────────────────────────
CREATE TABLE IF NOT EXISTS public.enrichment_conflicts (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id    BIGINT,
  ext           TEXT NOT NULL,
  attribute     TEXT NOT NULL,
  value_id      TEXT NOT NULL,
  value_label   TEXT NOT NULL DEFAULT '',
  -- ค่าที่ "หลักฐาน" บอกว่าเป็น (array ของ value_id)
  rule_values   JSONB NOT NULL DEFAULT '[]'::jsonb,
  ai_confidence NUMERIC(3,2),
  ai_quote      TEXT,
  -- ถ้าแท็กที่ขัดมาจากพจนานุกรมวลี → ใช้ปรับยอด accept/reject ตอนคนตัดสิน
  phrase_key    TEXT,
  evidence_type TEXT NOT NULL DEFAULT 'text'
                CHECK (evidence_type IN ('text', 'image')),
  severity      TEXT NOT NULL DEFAULT 'warning'
                CHECK (severity IN ('warning', 'critical')),
  reason        TEXT,
  status        TEXT NOT NULL DEFAULT 'pending'
                CHECK (status IN ('pending', 'resolved_rule', 'resolved_ai', 'dismissed')),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  resolved_at   TIMESTAMPTZ,
  resolved_by   TEXT,
  note          TEXT,
  UNIQUE (ext, attribute, value_id)
);

COMMENT ON TABLE public.enrichment_conflicts IS
  'คิวให้คนตรวจเมื่อค่าที่ AI ให้ขัดกับหลักฐาน — ระบบยึดหลักฐานเป็นตัวจริงจนกว่าคนจะตัดสิน';
COMMENT ON COLUMN public.enrichment_conflicts.status IS
  'pending = รอตรวจ · resolved_rule = ยึดหลักฐาน · resolved_ai = คนยืนยันค่า AI (เขียน attribute_overrides) · dismissed = ไม่ใช่ปัญหา';

CREATE INDEX IF NOT EXISTS idx_conflicts_status ON public.enrichment_conflicts(status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_conflicts_severity ON public.enrichment_conflicts(severity) WHERE status = 'pending';
CREATE INDEX IF NOT EXISTS idx_conflicts_ext ON public.enrichment_conflicts(ext);

ALTER TABLE public.enrichment_conflicts DISABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.enrichment_conflicts TO anon, authenticated;

