-- 1) ฟิลด์ normalized บนตาราง products (ไม่ทับข้อมูลเดิม)
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS brand TEXT;
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS product_type TEXT;
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS province TEXT;
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS region TEXT;
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS category_confidence NUMERIC;
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS quality_score INT;
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS quality_flags JSONB DEFAULT '[]'::jsonb;
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS network_node_key TEXT;

CREATE INDEX IF NOT EXISTS idx_products_brand ON public.products(brand);
CREATE INDEX IF NOT EXISTS idx_products_type ON public.products(product_type);
CREATE INDEX IF NOT EXISTS idx_products_province ON public.products(province);

-- 2) ประวัติการรัน pipeline
CREATE TABLE IF NOT EXISTS public.network_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  generated_at TIMESTAMPTZ DEFAULT NOW(),
  source TEXT,
  input_count INT DEFAULT 0,
  kept_count INT DEFAULT 0,
  dropped_count INT DEFAULT 0,
  merged_count INT DEFAULT 0,
  node_count INT DEFAULT 0,
  edge_count INT DEFAULT 0,
  quality_score INT,
  readiness INT,
  summary JSONB DEFAULT '{}'::jsonb
);

-- 3) Nodes (product / shop / brand / category / product_type / province / region)
CREATE TABLE IF NOT EXISTS public.network_nodes (
  id TEXT PRIMARY KEY,
  run_id BIGINT REFERENCES public.network_runs(id) ON DELETE CASCADE,
  type TEXT NOT NULL,
  label TEXT,
  weight NUMERIC DEFAULT 0,
  attributes JSONB DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS idx_network_nodes_type ON public.network_nodes(type);
CREATE INDEX IF NOT EXISTS idx_network_nodes_run ON public.network_nodes(run_id);

-- 4) Edges (sold_by / in_category / similar_to / substitute / complements ฯลฯ)
CREATE TABLE IF NOT EXISTS public.network_edges (
  id TEXT PRIMARY KEY,
  run_id BIGINT REFERENCES public.network_runs(id) ON DELETE CASCADE,
  type TEXT NOT NULL,
  source TEXT NOT NULL,
  target TEXT NOT NULL,
  weight NUMERIC DEFAULT 0,
  directed BOOLEAN DEFAULT FALSE,
  evidence JSONB DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS idx_network_edges_type ON public.network_edges(type);
CREATE INDEX IF NOT EXISTS idx_network_edges_source ON public.network_edges(source);
CREATE INDEX IF NOT EXISTS idx_network_edges_target ON public.network_edges(target);
CREATE INDEX IF NOT EXISTS idx_network_edges_run ON public.network_edges(run_id);

-- 5) RLS ให้สอดคล้องกับตารางอื่นในโปรเจกต์ (แอปเขียนผ่าน API ฝั่ง server)
ALTER TABLE public.network_runs DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.network_nodes DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.network_edges DISABLE ROW LEVEL SECURITY;

