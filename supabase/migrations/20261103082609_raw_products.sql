-- 1. สร้างตาราง raw_products (เก็บ JSON ดิบจาก Extension 100%)
CREATE TABLE IF NOT EXISTS public.raw_products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ext TEXT UNIQUE NOT NULL, -- ใช้เช็คข้อมูลซ้ำ
  payload JSONB NOT NULL,   -- เก็บ JSON ก้อนใหญ่จาก Extension
  status TEXT DEFAULT 'pending', -- pending | processed | failed
  error_message TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  processed_at TIMESTAMPTZ
);

-- 2. ปลดล็อก RLS (เพื่อให้ API ของเราบันทึกข้อมูลได้)
ALTER TABLE public.products DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.ingest_logs DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.raw_products DISABLE ROW LEVEL SECURITY;