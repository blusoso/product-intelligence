-- ==========================================
-- 1. สร้างตาราง Products (เวอร์ชันสมบูรณ์)
-- ==========================================
CREATE TABLE IF NOT EXISTS public.products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ext TEXT UNIQUE NOT NULL, -- คีย์หลักในการเช็คข้อมูลซ้ำ (shopee:shop_id:product_id)
  
  -- ข้อมูลพื้นฐาน (Core)
  product_id TEXT,
  shop_id TEXT,
  shop_name TEXT,
  sku TEXT,
  name TEXT NOT NULL,
  plat TEXT DEFAULT 'shopee',
  cat TEXT,
  url TEXT,
  
  -- ข้อมูลราคา & ค่าคอม
  price NUMERIC,
  price_before_discount NUMERIC,
  discount_pct INT,
  cm INT, -- ค่าคอม %
  t INT,  -- Trust Dots
  commission_per_unit NUMERIC,
  
  -- ข้อมูลยอดขาย & คะแนน
  monthly_sold INT DEFAULT 0,
  historical_sold INT DEFAULT 0,
  rating NUMERIC,
  review_count INT DEFAULT 0,
  trust_score INT DEFAULT 0,
  tier TEXT,
  liked_count INT DEFAULT 0,
  
  -- สถานะสินค้า & ร้านค้า
  location TEXT,
  shopee_verified BOOLEAN DEFAULT FALSE,
  is_ad BOOLEAN DEFAULT FALSE,
  listing_age_days INT,
  seller_flag TEXT,
  voucher_code TEXT,
  in_stock BOOLEAN,
  total_stock INT,
  enriched BOOLEAN DEFAULT FALSE,
  
  -- สถานะการทำงานในระบบ (Admin)
  st TEXT DEFAULT 'รอตรวจ',
  status TEXT DEFAULT 'pending',
  ingested_at TIMESTAMPTZ DEFAULT NOW(),
  last_ingested_at TIMESTAMPTZ,
  status_changed_at TIMESTAMPTZ,
  
  -- ข้อมูลซับซ้อน (เก็บเป็น JSONB เพื่อความเร็วและยืดหยุ่น)
  rating_dist JSONB DEFAULT '{}'::jsonb,
  trust_breakdown JSONB DEFAULT '{}'::jsonb,
  options JSONB DEFAULT '[]'::jsonb,
  images_all JSONB DEFAULT '[]'::jsonb,
  specs JSONB DEFAULT '[]'::jsonb,
  tier_variations JSONB DEFAULT '[]'::jsonb,
  reviews JSONB DEFAULT '[]'::jsonb,
  
  -- ข้อมูลดิบทั้งหมดจาก Extension
  _raw JSONB 
);

-- ==========================================
-- 2. สร้างตาราง Ingest Logs
-- ==========================================
CREATE TABLE IF NOT EXISTS public.ingest_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at TIMESTAMPTZ DEFAULT NOW(),
  source TEXT,
  keyword TEXT,
  added INT DEFAULT 0,
  updated INT DEFAULT 0,
  received INT DEFAULT 0
);

-- ==========================================
-- 3. ตั้งค่า Row Level Security (RLS)
-- ==========================================
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ingest_logs ENABLE ROW LEVEL SECURITY;

-- อนุญาตให้อ่านข้อมูลได้จากทุกที่
CREATE POLICY "Allow public read products" ON public.products FOR SELECT USING (true);
CREATE POLICY "Allow public read logs" ON public.ingest_logs FOR SELECT USING (true);