-- ═══════════════════════════════════════════════════════════════

-- 1) ฟิลด์ระดับ record บน products ─────────────────────────────
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS currency TEXT DEFAULT 'THB';
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS width_cm NUMERIC;
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS depth_cm NUMERIC;
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS height_cm NUMERIC;
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS size_label TEXT;

ALTER TABLE public.products ADD COLUMN IF NOT EXISTS canonical_id TEXT;
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS canonical_confidence NUMERIC;
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS listing_count INT DEFAULT 1;

-- เวลาที่เห็น listing ครั้งแรก (last_ingested_at คือครั้งล่าสุด)
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS first_ingested_at TIMESTAMPTZ;
UPDATE public.products
   SET first_ingested_at = COALESCE(first_ingested_at, ingested_at)
 WHERE first_ingested_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_products_canonical ON public.products(canonical_id);
CREATE INDEX IF NOT EXISTS idx_products_size ON public.products(width_cm, depth_cm);

-- 2) raw_products: แยก "เห็นครั้งแรก" / "เห็นล่าสุด" / จำนวนครั้งที่เปลี่ยน ──
ALTER TABLE public.raw_products ADD COLUMN IF NOT EXISTS first_seen_at TIMESTAMPTZ;
ALTER TABLE public.raw_products ADD COLUMN IF NOT EXISTS last_seen_at TIMESTAMPTZ;
ALTER TABLE public.raw_products ADD COLUMN IF NOT EXISTS version INT DEFAULT 1;

UPDATE public.raw_products
   SET first_seen_at = COALESCE(first_seen_at, created_at)
 WHERE first_seen_at IS NULL;
UPDATE public.raw_products
   SET last_seen_at = COALESCE(last_seen_at, processed_at, created_at)
 WHERE last_seen_at IS NULL;

-- 3) ประวัติ payload ดิบแบบ append-only (upsert ไม่ทับประวัติแล้ว) ─────────
CREATE TABLE IF NOT EXISTS public.raw_product_versions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ext TEXT NOT NULL,
  hash TEXT NOT NULL,
  payload JSONB NOT NULL,
  seen_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE (ext, hash)
);

CREATE INDEX IF NOT EXISTS idx_raw_versions_ext_seen
  ON public.raw_product_versions(ext, seen_at DESC);

ALTER TABLE public.raw_product_versions DISABLE ROW LEVEL SECURITY;

-- 4) ประวัติราคา (บันทึกเมื่อราคาเปลี่ยน) ────────────────────────────────
CREATE TABLE IF NOT EXISTS public.price_observations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ext TEXT NOT NULL,
  observed_at TIMESTAMPTZ DEFAULT NOW(),
  price NUMERIC NOT NULL,
  price_before_discount NUMERIC,
  monthly_sold INT DEFAULT 0,
  source TEXT
);

CREATE INDEX IF NOT EXISTS idx_price_obs_ext_time
  ON public.price_observations(ext, observed_at DESC);

ALTER TABLE public.price_observations DISABLE ROW LEVEL SECURITY;

